"""
B-Rep Round-Trip Test
=====================

Tests the full B-Rep pipeline:
  OCCBrep (STEP) -> IfcAdvancedBrep -> save IFC -> reload -> compare volume/area

Uses the 26 STEP files generated by scripts/8.1_brep_generate.py as input.
Each file is loaded as an OCCBrep, written to IFC via brep_to_IfcAdvancedBrep
(use_occ=True), then reloaded and compared geometrically.

Since there is no parametric reader for IfcAdvancedBrep, the read-back uses
ifcopenshell's geometry evaluator (visual_geometry) which returns an OCCBrep
when use_occ=True.  Geometric accuracy is verified by comparing volume and
surface area between the original and round-tripped geometry.

Known evaluator limitations (not converter bugs):
  - Periodic surfaces (sphere, torus): ifcopenshell may fail to evaluate or
    produce reversed solid orientation, giving zero/wrong volume.
  - Boolean-cut voids (hollow_box, box_with_hole): the converter flattens
    IfcAdvancedBrepWithVoids into IfcAdvancedBrep (single IfcClosedShell) for
    viewer compatibility, so the evaluator sees all faces as one shell without
    knowing which are voids.
  - NURBS fallback surfaces (cone, cone_truncated): conical surfaces are
    converted to NURBS (no IfcConicalSurface in IFC4), adding approximation.
  - Complex topology (capsule=boolean fuse, nurbs_pillow=extruded NURBS,
    pipe_sweep=swept circle): evaluation may fail or produce different topology.

Prerequisites:
  Run scripts/8.1_brep_generate.py first to generate STEP files in
  temp/brep_conversion_tests/

Run with:
  conda run -n compas-ifc python thesis/roundtrip_brep.py
"""

